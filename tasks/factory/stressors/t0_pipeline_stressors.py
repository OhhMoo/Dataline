"""Stage ten named t0 defects against a real theme-world DuckDB warehouse.

The sidecar uses a canonical event feed so every theme can exercise the same
contract.  It does not claim to mutate a theme's native DAT/XLSX/CSV loader.
The shipped pipeline's concrete choices are generated by ``oracle_composer``.
"""
from __future__ import annotations

import csv
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

import duckdb

from .domain_schema_adapter import FALLBACK_TABLES


STRESSORS = {
    "S01": "checkpoint_calendar_advance_on_gap",
    "S02": "checkpoint_filter_blocks_backfill",
    "S03": "retry_batch_append_without_dedup",
    "S04": "delivered_at_beats_version_precedence",
    "S05": "void_folded_as_zero_row_instead_of_excluded",
    "S06": "fanout_join_in_mart_or_bi",
    "S07": "quality_gate_inner_join_drops_valid_null_fk",
    "S08": "stale_pre_cutover_tax_or_fx_formula",
    "S09": "scheduler_dag_dependency_inverted",
    "S10": "closed_window_unconditional_delete_reinsert",
}

FIELDS = ["event_id", "delivered_at", "business_day", "business_id",
          "version", "event_type", "entity_id", "amount_cents"]

_TABLE_DDL = {
    "raw": """(
            event_id VARCHAR, delivered_at TIMESTAMP, business_day DATE,
            business_id VARCHAR, version INTEGER, event_type VARCHAR,
            entity_id VARCHAR, amount_cents BIGINT, source_partition VARCHAR)""",
    "fact": """(
            business_id VARCHAR, business_day DATE, entity_id VARCHAR,
            amount_cents BIGINT, version INTEGER)""",
    "handoff": """(
            business_day DATE, entity_id VARCHAR, payments BIGINT,
            net_cents BIGINT, correction_ref VARCHAR)""",
    "close": """(
            business_day DATE, entity_id VARCHAR, payments BIGINT,
            net_cents BIGINT)""",
    "corrections": """(
            business_day DATE, ticket VARCHAR, approved_by VARCHAR)""",
    "checkpoint": "(through_day DATE)",
}

_TABLE_COLUMNS = {
    "raw": ["event_id", "delivered_at", "business_day", "business_id", "version",
            "event_type", "entity_id", "amount_cents", "source_partition"],
    "fact": ["business_id", "business_day", "entity_id", "amount_cents", "version"],
    "handoff": ["business_day", "entity_id", "payments", "net_cents", "correction_ref"],
    "close": ["business_day", "entity_id", "payments", "net_cents"],
    "corrections": ["business_day", "ticket", "approved_by"],
    "checkpoint": ["through_day"],
}


def _usable(con, name: str, columns: list[str]) -> bool:
    col_sql = ", ".join(columns)
    try:
        con.execute(f"SELECT {col_sql} FROM {name} WHERE 1 = 0")
    except duckdb.Error:
        return False
    return True


def _create_table(con, name: str, ddl: str) -> None:
    schema = name.split(".", 1)[0]
    con.execute(f"CREATE SCHEMA IF NOT EXISTS {schema}")
    con.execute(f"CREATE TABLE {name} {ddl}")


def ensure_table(con, preferred: str, fallback: str, kind: str) -> str:
    """Create ``preferred`` when the warehouse can hold the feed columns.

    A theme table that already exists with a different shape is left alone.
    The feed then uses ``fallback`` so a built world is not rewritten.
    """
    columns = _TABLE_COLUMNS[kind]
    ddl = _TABLE_DDL[kind]
    if _usable(con, preferred, columns):
        con.execute(f"DELETE FROM {preferred}")
        return preferred
    try:
        _create_table(con, preferred, ddl)
        return preferred
    except duckdb.Error:
        if preferred == fallback:
            raise
    if _usable(con, fallback, columns):
        con.execute(f"DELETE FROM {fallback}")
        return fallback
    _create_table(con, fallback, ddl)
    return fallback


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def _row(seq: str, day: date, *, bid: str | None = None,
         version: int | str = 1, kind: str = "settle",
         entity: str = "ORG-A", amount: int = 1000,
         delivered: str | None = None) -> dict:
    return {"event_id": f"EV-{seq}",
            "delivered_at": delivered or f"{day.isoformat()}T04:00:00+00:00",
            "business_day": day.isoformat(), "business_id": bid or f"B-{seq}",
            "version": version, "event_type": kind, "entity_id": entity,
            "amount_cents": amount}


def _world_day(world: Path) -> date:
    import json
    state = json.loads((world / "var/sched/state.json").read_text())
    value = state["vnow"].replace("Z", "+00:00")
    return datetime.fromisoformat(value).astimezone(timezone.utc).date()


def apply_stressors(world_dir: Path, stressor_ids: list[str] | tuple[str, ...],
                    *, seed: int, governance_mode: str,
                    closed_day: str | None = None, ticket: str | None = None,
                    controller: str = "controller",
                    landing_dir: str = "data/factory_feed",
                    tables: dict | None = None) -> dict:
    """Create the feed and warehouse tables for the selected t0 defects.

    ``tables`` names the preferred raw/fact/handoff/close/corrections/checkpoint
    relations. A missing or incompatible relation falls back to the factory
    sidecar name. Re-applying to a fresh world with the same seed produces
    identical feed bytes.
    """
    world = Path(world_dir)
    ids = list(stressor_ids)
    unknown = set(ids) - STRESSORS.keys()
    if unknown:
        raise ValueError(f"unknown stressors: {sorted(unknown)}")
    if not ids:
        raise ValueError("at least one t0 stressor is required")
    t0 = _world_day(world)
    historical = date.fromisoformat(closed_day) if closed_day else t0 - timedelta(days=3)
    if historical >= t0 - timedelta(days=1):
        raise ValueError("closed_day must precede the t0 feed day")
    approved_day = historical + timedelta(days=1)
    feed_day = t0 - timedelta(days=1)
    preferred = {**FALLBACK_TABLES, **(tables or {})}
    feed = world / "workspace" / landing_dir
    # Both closed days have an immutable published snapshot.  An approved
    # correction is possible on one; the other is deliberately protected.
    old = [
        _row(f"CLOSED-{seed}", historical, bid=f"B-CLOSED-{seed}", amount=1000),
        _row(f"APPROVED-{seed}", approved_day,
             bid=f"B-APPROVED-{seed}", amount=1500),
    ]
    special = [
        _row(f"NORMAL-{seed}", feed_day, amount=2000),
        _row(f"FANOUT-{seed}", feed_day, amount=1210),
        _row(f"NULLFK-{seed}", feed_day, entity="", amount=880),
        _row(f"CUTOVER-{seed}", feed_day, amount=2300),
        _row(f"VOID-{seed}-V1", feed_day, bid=f"B-VOID-{seed}", amount=900),
        _row(f"VOID-{seed}-V2", feed_day, bid=f"B-VOID-{seed}", version=2,
             kind="void", amount=0, delivered=f"{feed_day}T05:00:00+00:00"),
        _row(f"ORDER-{seed}-V2", feed_day, bid=f"B-ORDER-{seed}",
             version=2, amount=3300,
             delivered=f"{feed_day}T06:00:00+00:00"),
        _row(f"ORDER-{seed}-V1", feed_day, bid=f"B-ORDER-{seed}",
             amount=1700, delivered=f"{feed_day}T07:00:00+00:00"),
        _row(f"CLOSED-{seed}-V2", feed_day, bid=f"B-CLOSED-{seed}",
             version=2, amount=1250, delivered=f"{feed_day}T08:00:00+00:00"),
        _row(f"APPROVED-{seed}-V2", feed_day,
             bid=f"B-APPROVED-{seed}", version=2, amount=1800,
             delivered=f"{feed_day}T08:00:00+00:00"),
    ]
    special[-2]["business_day"] = historical.isoformat()
    special[-1]["business_day"] = approved_day.isoformat()
    _write_csv(feed / f"dt={historical}" / "events.csv", [old[0]])
    _write_csv(feed / f"dt={approved_day}" / "events.csv", [old[1]])
    _write_csv(feed / f"dt={feed_day}" / "events.csv", special)
    backfill = _row(f"BACKFILL-{seed}", historical,
                    bid=f"B-BACKFILL-{seed}", amount=770)
    _write_csv(feed / f"dt={historical}" / "events-recovery.csv", [backfill])
    if "S03" in ids:
        # Keep both physical deliveries at t0. The shipped reader loads both;
        # the repaired reader selects one event_id from the primary batch.
        _write_csv(feed / f"dt={feed_day}" / "events-retry.csv", [special[0]])

    db = world / "var/warehouse/warehouse.duckdb"
    con = duckdb.connect(":memory:", config={"threads": 1})
    con.execute("ATTACH '" + str(db).replace("'", "''") + "' AS wh")
    con.execute("USE wh")
    try:
        physical = {
            kind: ensure_table(con, preferred[kind], FALLBACK_TABLES[kind], kind)
            for kind in ("raw", "fact", "handoff", "close", "corrections", "checkpoint")
        }
        for row in old:
            con.execute(
                f"INSERT INTO {physical['close']} "
                "(business_day, entity_id, payments, net_cents) VALUES (?, ?, 1, ?)",
                [row["business_day"], row["entity_id"], row["amount_cents"]])
            con.execute(
                f"INSERT INTO {physical['handoff']} "
                "(business_day, entity_id, payments, net_cents, correction_ref) "
                "VALUES (?, ?, 1, ?, NULL)",
                [row["business_day"], row["entity_id"], row["amount_cents"]])
        if governance_mode == "act-authorized":
            con.execute(
                f"INSERT INTO {physical['corrections']} "
                "(business_day, ticket, approved_by) VALUES (?, ?, ?)",
                [str(historical), ticket or f"FACT-{seed}", controller])
        # S01 and S02 leave the corrupt watermark on the feed day (t0 minus
        # one day), not on the scheduler's later calendar day. The feed-day
        # folder stays on disk. The incremental gate skips day<=through, so
        # the initial raw load does not contain dt=feed_day.
        checkpoint = feed_day if set(ids) & {"S01", "S02"} else historical - timedelta(days=1)
        con.execute(
            f"INSERT INTO {physical['checkpoint']} (through_day) VALUES (?)",
            [str(checkpoint)])
    finally:
        con.close()
    return {
        "dates": {"t0": str(t0), "historical": str(historical),
                  "approved": str(approved_day), "feed": str(feed_day)},
        "tables": [physical["raw"], physical["fact"], physical["handoff"],
                   physical["checkpoint"]],
        "physical_tables": physical,
        "landing_dir": landing_dir,
        "stressor_ids": ids,
        "authority": {"ticket": ticket or f"FACT-{seed}",
                      "controller": controller, "closed_day": str(historical)},
    }
