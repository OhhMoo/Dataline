"""Regenerate gateway/requirements-snowflake.lock (the Snowflake plug's clients).

    gateway/.venv/bin/python gateway/docker/lock_snowflake_clients.py

dbt-snowflake caps certifi below 2025.4.26, so it cannot be resolved inside
gateway/uv.lock without holding back every image's CA bundle (pyproject's
`snowflake` extra says why). It is compiled here instead, against every version
the base, native and ds locks pin - so a package the clients share with them is
the SAME version and installing this lock after them changes nothing else - with
certifi the one deliberate exception, taken from snowflake-clients.overrides.
"""
from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

GATEWAY = Path(__file__).resolve().parent.parent
DOCKER = GATEWAY / "docker"
CONSTRAINED_BY = ("requirements.lock", "requirements-native.lock", "requirements-ds.lock")
#: Packages whose pins the clients may NOT inherit; each needs a line in
#: snowflake-clients.overrides saying what it is held to instead.
DIVERGES = frozenset({"certifi"})
OUTPUT = GATEWAY / "requirements-snowflake.lock"
PIN = re.compile(r"^([A-Za-z0-9_.\-\[\]]+)==([^ ;\\]+)(\s*;[^\\]*)?")


def constraints() -> str:
    """`name==version[; marker]` for every pin in CONSTRAINED_BY except DIVERGES."""
    lines = []
    for name in CONSTRAINED_BY:
        for line in (GATEWAY / name).read_text(encoding="utf-8").splitlines():
            m = PIN.match(line)
            if m and m.group(1).lower() not in DIVERGES:
                lines.append(f"{m.group(1)}=={m.group(2)}{m.group(3) or ''}".rstrip())
    return "\n".join(sorted(set(lines))) + "\n"


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        pins = Path(tmp) / "base-pins.txt"
        pins.write_text(constraints(), encoding="utf-8")
        argv = ["uv", "pip", "compile", "snowflake-clients.in", "--universal",
                "--generate-hashes", "--python-version", "3.11",
                "--constraint", str(pins),
                "--overrides", "snowflake-clients.overrides",
                "--no-header", "--output-file", str(OUTPUT)]
        result = subprocess.run(argv, cwd=DOCKER, capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stderr, file=sys.stderr)
            return result.returncode
    header = ("# This file was autogenerated by gateway/docker/lock_snowflake_clients.py:\n"
              "#    gateway/.venv/bin/python gateway/docker/lock_snowflake_clients.py\n"
              "# (uv pip compile docker/snowflake-clients.in, constrained to "
              f"{', '.join(CONSTRAINED_BY)} except {', '.join(sorted(DIVERGES))})\n")
    OUTPUT.write_text(header + OUTPUT.read_text(encoding="utf-8"), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
