"""Regenerate gateway/requirements-<name>.lock, a backend's client libraries.

    gateway/.venv/bin/python gateway/docker/lock_warehouse_clients.py <name>

A backend's clients (`clients` in alkera_gateway.backends) are compiled apart
from gateway/uv.lock: a vendor adapter that caps a shared package (dbt-snowflake
caps certifi below 2025.4.26) would otherwise hold back every image. They are
compiled here instead, from gateway/docker/<name>-clients.in, against every
version the base, native and ds locks pin - so a package the clients share with
them is the SAME version and installing this lock after them changes nothing
else - with DIVERGES the only packages allowed another version, each held to
what gateway/docker/<name>-clients.overrides says.

The output is a function of its inputs: uv runs in a scratch directory holding
copies of the .in and .overrides files and the base pins under fixed names, so
no temporary path is written into the lock, and two runs over one PyPI state
are the same bytes.

Every Dockerfile build installs requirements-<c>.lock for each `c` in
ALKERA_WAREHOUSE_CLIENTS (build_episode.py --warehouse-clients).
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

GATEWAY = Path(__file__).resolve().parent.parent
DOCKER = GATEWAY / "docker"
CONSTRAINED_BY = ("requirements.lock", "requirements-native.lock", "requirements-ds.lock")
#: Packages whose pins the clients may NOT inherit; each needs a line in
#: <name>-clients.overrides saying what it is held to instead.
DIVERGES = frozenset({"certifi"})
PIN = re.compile(r"^([A-Za-z0-9_.\-\[\]]+)==([^ ;\\]+)(\s*;[^\\]*)?")
#: The base pins' name inside the scratch directory, which is what the lock's
#: `# via -c ...` annotations then say.
PINS = "base-pins.txt"
#: Client sets whose lock predates this script and names its own entry point
#: in the header; regenerating them keeps that header, so the bytes stay.
ENTRY_POINTS = {"snowflake": "lock_snowflake_clients.py"}


def constraints() -> str:
    """`name==version[; marker]` for every pin in CONSTRAINED_BY except DIVERGES."""
    lines = []
    for name in CONSTRAINED_BY:
        for line in (GATEWAY / name).read_text(encoding="utf-8").splitlines():
            m = PIN.match(line)
            if m and m.group(1).lower() not in DIVERGES:
                lines.append(f"{m.group(1)}=={m.group(2)}{m.group(3) or ''}".rstrip())
    return "\n".join(sorted(set(lines))) + "\n"


def sources(name: str) -> tuple[Path, Path | None]:
    """`<name>-clients.in` (required) and `<name>-clients.overrides` (optional)."""
    requirements = DOCKER / f"{name}-clients.in"
    if not requirements.is_file():
        raise SystemExit(f"no {requirements.relative_to(GATEWAY.parent)}: a client set "
                         f"is declared by its .in file")
    overrides = DOCKER / f"{name}-clients.overrides"
    return requirements, overrides if overrides.is_file() else None


def output(name: str) -> Path:
    return GATEWAY / f"requirements-{name}.lock"


def header(name: str) -> str:
    script = ENTRY_POINTS.get(name)
    command = (f"gateway/docker/{script}" if script
               else f"gateway/docker/lock_warehouse_clients.py {name}")
    return (f"# This file was autogenerated by gateway/docker/"
            f"{script or 'lock_warehouse_clients.py'}:\n"
            f"#    gateway/.venv/bin/python {command}\n"
            f"# (uv pip compile docker/{name}-clients.in, constrained to "
            f"{', '.join(CONSTRAINED_BY)} except {', '.join(sorted(DIVERGES))})\n")


def compile_argv(name: str, overrides: bool, out: Path) -> list[str]:
    argv = ["uv", "pip", "compile", f"{name}-clients.in", "--universal",
            "--generate-hashes", "--python-version", "3.11", "--constraint", PINS]
    if overrides:
        argv += ["--overrides", f"{name}-clients.overrides"]
    return argv + ["--no-header", "--output-file", str(out)]


def lock(name: str) -> int:
    requirements, overrides = sources(name)
    target = output(name)
    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp)
        (scratch / PINS).write_text(constraints(), encoding="utf-8")
        shutil.copyfile(requirements, scratch / requirements.name)
        if overrides is not None:
            shutil.copyfile(overrides, scratch / overrides.name)
        compiled = scratch / "compiled.lock"
        if target.is_file():
            # `uv pip compile --output-file` prefers the pins already in the
            # file it rewrites (pip-tools semantics), so a regeneration moves
            # only what an input change forces - the existing lock goes where
            # uv will look for it.
            shutil.copyfile(target, compiled)
        result = subprocess.run(compile_argv(name, overrides is not None, compiled),
                                cwd=scratch, capture_output=True, text=True)
        if result.returncode != 0:
            print(result.stderr, file=sys.stderr)
            return result.returncode
        body = compiled.read_text(encoding="utf-8")
    with open(target, "w", encoding="utf-8", newline="") as stream:
        stream.write(header(name) + body)
    print(f"wrote {target}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("name", help="the client set: gateway/docker/<name>-clients.in")
    return lock(parser.parse_args(argv).name)


if __name__ == "__main__":
    raise SystemExit(main())
